"""Shared IO helpers for Stage code — context-aware paths, upstream reads, logging.

All stages generated by exp-stages must use these helpers instead of
hardcoded paths or bare ``except: pass`` blocks.

Contract:
- Paths resolve from ``DATA_DIR`` / ``OUTPUT_DIR`` env at *runtime*
  (respects Colab mount-cell override set before ``import src.stages``).
- Inter-stage reads go through ``manifest_index.json`` (single source of
  truth) via :func:`load_upstream`; never hardcode a sibling preview path.
- Logs land under ``OUTPUT_DIR/logs`` (MCP-readable from Drive):
  one ``run_{stage}_{timestamp}.log`` per execution plus an appended
  ``errors.json`` list (never overwritten).
- Manifest writes are atomic (tmp + rename) so a dropped Colab tab never
  leaves a half-written ``*_manifest.json`` behind.
"""

import json
import os
from datetime import datetime, timezone
from pathlib import Path


def get_output_base() -> Path:
    """Return OUTPUT_DIR base (runtime env, Colab-override aware)."""
    return Path(os.environ.get("OUTPUT_DIR", "../outputs"))


def get_data_dir() -> Path:
    """Return DATA_DIR base (runtime env, Colab-override aware)."""
    return Path(os.environ.get("DATA_DIR", "../data"))


def get_index_path() -> Path:
    """Return path to manifest_index.json under OUTPUT_DIR."""
    return get_output_base() / "manifest_index.json"


def resolve_context() -> dict:
    """Describe where this code runs (observe only, never branch logic).

    Returns dict with context label (``colab`` when /content/drive exists,
    else ``local``), resolved DATA_DIR / OUTPUT_DIR / index path.
    Stages must log this at run start so Drive/local mixups are visible.
    """
    in_colab = Path("/content/drive").exists()
    return {
        "context": "colab" if in_colab else "local",
        "data_dir": Path(get_data_dir()).as_posix(),
        "output_dir": Path(get_output_base()).as_posix(),
        "index_path": get_index_path().as_posix(),
    }


def load_index() -> dict:
    """Load manifest_index.json as dict (migrates legacy list read-only)."""
    index_path = get_index_path()
    if not index_path.exists():
        return {}
    try:
        data = json.loads(index_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    if isinstance(data, dict):
        return data
    if isinstance(data, list):
        migrated: dict = {}
        for item in data:
            if not isinstance(item, dict):
                continue
            key = item.get("stage")
            if not key:
                continue
            old_path = item.get("path", "")
            migrated[key] = {
                "seccion_paper": item.get("seccion_paper", ""),
                "output_dir": Path(old_path).as_posix() if old_path else "",
                "manifest": {"_migrated_keys": item.get("keys_principales", [])},
            }
        return migrated
    return {}


def load_upstream(stage: str, key: str | None = None, artifact: str | None = None, required: bool = True):
    """Load upstream stage output via the index (hybrid metadata + artifact).

    Args:
        stage: upstream registry name (e.g. ``split``, ``feature_selection``).
        key: manifest key to return (e.g. ``best_params``, ``selected_features``).
        artifact: filename under the upstream output_dir (e.g. ``split_map.csv``).
        required: when True (default) raise with a ``run <stage> first`` hint
            if the upstream entry/key/artifact is missing (fail-fast, never
            silent placeholders). When False return None instead.

    Returns the manifest value, the artifact Path, or a (value, path) tuple
    when both key and artifact are given.
    """
    index = load_index()
    entry = index.get(stage)
    if not isinstance(entry, dict):
        if required:
            raise RuntimeError(f"upstream stage '{stage}' not in manifest_index.json - run it first (main.py --stage {stage})")
        return None
    manifest = entry.get("manifest", {})
    upstream_dir = Path(entry.get("output_dir", "")) if entry.get("output_dir") else None

    value = None
    if key is not None:
        if not isinstance(manifest, dict) or key not in manifest:
            if required:
                raise RuntimeError(f"upstream '{stage}' manifest lacks key '{key}' - re-run it first (main.py --stage {stage})")
            return None
        value = manifest[key]

    path = None
    if artifact is not None:
        if upstream_dir is None:
            if required:
                raise RuntimeError(f"upstream '{stage}' has no output_dir in index — re-run it first")
            return None
        # Resolve the artifact path from the index output_dir (never hardcoded).
        path = upstream_dir / artifact
        if not path.exists():
            # Fall back to current OUTPUT_DIR base + recorded subfolder tail so a
            # Drive/local base swap still resolves (index stores absolute Drive
            # paths from Colab; local runs use ../outputs).
            try:
                tail = Path(entry.get("output_dir", "")).name
                alt = get_output_base() / tail / artifact
                if alt.exists():
                    path = alt
            except OSError:
                pass
        if not path.exists() and required:
            raise RuntimeError(f"upstream artifact '{stage}/{artifact}' missing at {path} — run it first (main.py --stage {stage})")
        if not path.exists():
            return value

    if key is not None and artifact is not None:
        return value, path
    if key is not None:
        return value
    return path


def new_run_log(stage: str) -> Path:
    """Create OUTPUT_DIR/logs/run_{stage}_{UTC timestamp}.log with header."""
    log_dir = get_output_base() / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    log_path = log_dir / f"run_{stage}_{stamp}.log"
    ctx = resolve_context()
    header = f"[start] stage={stage} utc={stamp} context={ctx['context']} DATA_DIR={ctx['data_dir']} OUTPUT_DIR={ctx['output_dir']}\n"
    try:
        log_path.write_text(header, encoding="utf-8")
    except OSError:
        pass
    return log_path


def log_line(log_path: Path, message: str) -> None:
    """Append one line to a run log (best effort, never raises)."""
    try:
        with open(log_path, "a", encoding="utf-8") as f:
            f.write(message.rstrip("\n") + "\n")
    except OSError:
        pass


def append_errors_entry(entry: dict) -> None:
    """Append one entry to OUTPUT_DIR/logs/errors.json list (never overwrite)."""
    log_dir = get_output_base() / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    errors_path = log_dir / "errors.json"
    data = []
    if errors_path.exists():
        try:
            raw = json.loads(errors_path.read_text(encoding="utf-8"))
            if isinstance(raw, list):
                data = raw
            elif isinstance(raw, dict):
                data = [raw]
        except (json.JSONDecodeError, OSError):
            data = []
    if "utc" not in entry:
        entry["utc"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    data.append(entry)
    tmp = errors_path.with_suffix(".tmp")
    try:
        tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        tmp.replace(errors_path)
    except OSError:
        pass


def write_manifest_atomic(output_dir: str | Path, filename: str, manifest: dict) -> Path:
    """Write manifest JSON atomically (tmp + rename) and return its path."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    target = out / filename
    tmp = out / (filename + ".tmp")
    tmp.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(target)
    return target


def read_manifest(output_dir: str | Path, filename: str) -> dict | None:
    """Read a manifest file; return None when missing or corrupt."""
    target = Path(output_dir) / filename
    if not target.exists():
        return None
    try:
        data = json.loads(target.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    return data if isinstance(data, dict) and data else None


def update_checkpoint_manifest(stage: str, ckpt_name: str, meta: dict) -> None:
    """Record a checkpoint pointer for long stages (Optuna/train resume)."""
    ckpt_cfg_dir = get_output_base() / "checkpoints"
    ckpt_cfg_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = ckpt_cfg_dir / "checkpoint_manifest.json"
    data: dict = {}
    if manifest_path.exists():
        try:
            raw = json.loads(manifest_path.read_text(encoding="utf-8"))
            if isinstance(raw, dict):
                data = raw
        except (json.JSONDecodeError, OSError):
            data = {}
    data[stage] = {
        "ckpt": ckpt_name,
        "utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        **meta,
    }
    tmp = manifest_path.with_suffix(".tmp")
    try:
        tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        tmp.replace(manifest_path)
    except OSError:
        pass


def build_target(df, train_years, target_col: str = "riesgo_congestion"):
    """Build the P75/P25 proxy target (config data.target, OUR formula).

    y=1[s>=q75(s_train) and t<=q25(t_train)], s=ingresado-atendido,
    t=atendido/ingresado. Thresholds exclusively from the train_years block,
    applied to all rows. Requires ingresado/atendido/anio columns.
    Returns (frame with target column, y ndarray int, q75, q25, prevalence).
    Lazy pandas/numpy import keeps this module dependency-light otherwise.
    """
    import numpy as np
    import pandas as pd

    frame = df.copy()
    frame["ingresado"] = pd.to_numeric(frame["ingresado"], errors="coerce")
    frame["atendido"] = pd.to_numeric(frame["atendido"], errors="coerce").fillna(0.0)
    frame = frame.dropna(subset=["ingresado"])
    frame = frame[frame["ingresado"] > 0]
    s = (frame["ingresado"] - frame["atendido"]).to_numpy(dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        t = np.where(frame["ingresado"].to_numpy(dtype=float) > 0, frame["atendido"].to_numpy(dtype=float) / frame["ingresado"].to_numpy(dtype=float), 0.0)
    mask = frame["anio"].isin(list(train_years)).to_numpy()
    if not mask.any():
        raise ValueError(f"build_target: no rows in train_years={list(train_years)}")
    q75 = float(np.quantile(s[mask], 0.75))
    q25 = float(np.quantile(t[mask], 0.25))
    y = ((s >= q75) & (t <= q25)).astype(int)
    frame[target_col] = y
    prevalence = float(y[mask].mean())
    return frame, y, q75, q25, prevalence


def fit_encoding_maps(frame, cat_cols, fit_mask, max_cardinality):
    """Decide one-hot vs frequency per categorical column (fit block only).

    Shared contract for feature_selection and split: train nunique within the
    limit goes one-hot (sorted categories), the rest goes frequency. Single
    source of truth — stages must import this, never copy it.
    Returns (one_hot_cols, one_hot_categories, frequency_cols, frequency_maps).
    """
    one_hot_cols, frequency_cols = [], []
    one_hot_categories, frequency_maps = {}, {}
    for col in cat_cols:
        train_values = frame.loc[fit_mask, col].fillna("missing").astype(str)
        if int(train_values.nunique()) <= int(max_cardinality):
            one_hot_cols.append(col)
            one_hot_categories[col] = sorted(train_values.unique().tolist())
        else:
            frequency_cols.append(col)
            frequency_maps[col] = {str(k): float(v) for k, v in train_values.value_counts(normalize=True).items()}
    return one_hot_cols, one_hot_categories, frequency_cols, frequency_maps


def apply_encoding(frame, num_cols, one_hot_cols, one_hot_categories, frequency_cols, frequency_maps):
    """Encode a block with fitted maps; unseen categories become zeros.

    Output is float with deterministic column order: numerics as given, then
    one-hot expansions (categories sorted), then frequency columns.
    """
    import pandas as pd

    encoded = pd.DataFrame(index=frame.index)
    for col in num_cols:
        encoded[col] = pd.to_numeric(frame[col], errors="coerce").fillna(0.0).astype(float)
    for col in one_hot_cols:
        series = frame[col].fillna("missing").astype(str)
        for category in one_hot_categories[col]:
            encoded[f"{col}__{category}"] = (series == category).astype(float)
    for col in frequency_cols:
        mapping = frequency_maps[col]
        encoded[f"freq_{col}"] = frame[col].fillna("missing").astype(str).map(mapping).fillna(0.0).astype(float)
    return encoded
